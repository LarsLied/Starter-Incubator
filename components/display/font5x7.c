static const uint8_t s_degree[FONT5X7_HEIGHT] = {0x0C, 0x12, 0x12, 0x0C, 0x00, 0x00, 0x00};

const uint8_t *font5x7_next_glyph(const char **text)
{
    const unsigned char c = (unsigned char)**text;
    (*text)++;

    // UTF-8 degree sign is the two bytes 0xC2 0xB0
    if (c == 0xC2 && (unsigned char)**text == 0xB0) {
        (*text)++;
        return s_degree;
    }

    const int upper = toupper(c);
    if (upper < FIRST_CHAR || upper > LAST_CHAR) {
        return s_font[0];  // blank
    }
    return s_font[upper - FIRST_CHAR];
}
